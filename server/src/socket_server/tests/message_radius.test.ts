/**
 * This code tests to make sure a client's message reaches all users within 100 m, and only those users.
 *
 * The tests cover eight clusters: two in each of the four quandrants of the Earth.
 * For each quadrant of the Earth, one cluster of coordinates is in range and the other cluster of coordinates is not in range.
 * 
 * The tests also cover specific edge cases including the prime meridian, the antimeridian, the north pole, and the south pole.
 */
import { sendMessage } from "../methods/send_message";
import { updateLocation } from "../methods/update_location";
import { initRegions } from "../regions";
import { ConnectionContext } from "../socket_server";
import { Location, Message } from "../../types";

type Point = [lat: number, lon: number];

/** First we connect the client and register their location. **/
const connectAt = (uid: string, [lat, lon]: Point): ConnectionContext => {
  const socket = { id: uid, emit: jest.fn() } as any;
  const ctx: ConnectionContext = {
    socket,
    user: { socket, uid, location: { lat: 0, lon: 0, geohash: "" }, profile: { displayName: uid, profilePicture: 0 } },
  };
  updateLocation(ctx, { lat, lon }, undefined);
  return ctx;
};

/** Send a message from `sender` (at the sender's own location); return it. **/
const send = (sender: ConnectionContext): Message => {
  const message = { id: `msg-${sender.user.uid}`, author: sender.user.uid, content: { text: "hi" }, reactions: {} } as Message;
  sendMessage(sender, message, undefined);
  return message;
};

/** Messages a client's socket actually received. **/
const received = (ctx: ConnectionContext): Message[] =>
  (ctx.socket.emit as jest.Mock).mock.calls.filter((c) => c[0] === "message").map((c) => c[1]);

/** Every point sends in turn; every OTHER point must receive it (inRange) or not (!inRange). **/
const checkCluster = (points: Point[], inRange: boolean) => {
  const clients = points.map((p, i) => connectAt(`p${i + 1}`, p));
  for (const sender of clients) {
    const message = send(sender);
    for (const client of clients) {
      if (client === sender) continue;
      expect(received(client).includes(message)).toBe(inRange);
    }
  }
};

/** `a` sends; `b` must receive it (inRange) or not (!inRange). **/
const checkPair = (a: Point, b: Point, inRange: boolean) => {
  const sender = connectAt("a", a);
  const receiver = connectAt("b", b);
  const message = send(sender);
  expect(received(receiver).includes(message)).toBe(inRange);
};

